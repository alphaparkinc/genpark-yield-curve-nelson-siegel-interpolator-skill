import sys, json
from client import NelsonSiegelYieldCurve

ns = NelsonSiegelYieldCurve()

def handle_jsonrpc(line):
    global ns
    try:
        req = json.loads(line)
        req_id = req.get("id")
        method = req.get("method")
        if method == "initialize":
            return {"jsonrpc": "2.0", "id": req_id, "result": {"protocolVersion": "2024-11-05", "serverInfo": {"name": "genpark-yield-curve-nelson-siegel-interpolator-skill", "version": "1.0.0"}, "capabilities": {"tools": {}}}}
        elif method == "tools/list":
            return {"jsonrpc": "2.0", "id": req_id, "result": {"tools": [
                {"name": "generate_curve", "description": "Generate zero-coupon curve points.", "inputSchema": {"type": "object", "properties": {"maturities": {"type": "array"}}, "required": ["maturities"]}},
                {"name": "benchmark_yield_curve", "description": "Run yield curve benchmark.", "inputSchema": {"type": "object", "properties": {}}}
            ]}}
        elif method == "tools/call":
            params = req.get("params", {})
            tool = params.get("name")
            args = params.get("arguments", {})
            if tool == "generate_curve":
                res = {"curve": ns.generate_curve(args.get("maturities", []))}
            elif tool == "benchmark_yield_curve":
                res = ns.benchmark_yield_curve()
            else:
                return {"jsonrpc": "2.0", "id": req_id, "error": {"code": -32601, "message": "Method not found"}}
            return {"jsonrpc": "2.0", "id": req_id, "result": {"content": [{"type": "text", "text": json.dumps(res, indent=2)}]}}
        return {"jsonrpc": "2.0", "id": req_id, "result": {}}
    except Exception as e:
        return {"jsonrpc": "2.0", "id": None, "error": {"code": -32603, "message": str(e)}}

def main():
    for line in sys.stdin:
        if line.strip():
            print(json.dumps(handle_jsonrpc(line.strip())), flush=True)

if __name__ == "__main__":
    main()
